export function mergeFoodLabelTraining(data) {
  const hasSop = (data.sops || []).some((row) => row.id === FOOD_LABEL_SOP_ID || row.sop_code === FOOD_LABEL_SOP.sop_code)
  const hasCourse = (data.courses || []).some((row) => row.id === FOOD_LABEL_COURSE_ID)
  const hasQuiz = (data.quizzes || []).some((row) => row.id === FOOD_LABEL_QUIZ_ID)

  return {
    ...data,
    sops: hasSop ? data.sops : [FOOD_LABEL_SOP, ...(data.sops || [])],
    steps: hasSop ? data.steps : [...FOOD_LABEL_STEPS, ...(data.steps || [])],
    courses: hasCourse ? data.courses : [FOOD_LABEL_COURSE, ...(data.courses || [])],
    lessons: hasCourse ? data.lessons : [...FOOD_LABEL_LESSONS, ...(data.lessons || [])],
    quizzes: hasQuiz ? data.quizzes : [FOOD_LABEL_QUIZ, ...(data.quizzes || [])],
    questions: hasQuiz ? data.questions : [...FOOD_LABEL_QUESTIONS, ...(data.questions || [])],
  }
}
