import { createHash } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import process from 'node:process'

function usage() {
  console.error(`Usage:
  node scripts/ops/build-safe-backfill.mjs \\
    --entity StockCount \\
    --input /private/path/records.json \\
    --output /private/path/backfill.sql \\
    [--id-field id] \\
    [--outlet-field outlet_id] \\
    [--business-date-field count_date] \\
    [--status-field status] \\
    [--normalize-deleted-at-sentinels 35,99,210]

Input must be either a JSON array of records or { "records": [...] }.
The tool generates SQL and evidence only. It never connects to D1.`)
  process.exit(2)
}

const args = process.argv.slice(2)
const options = {}
for (let index = 0; index < args.length; index += 1) {
  const key = args[index]
  if (!key.startsWith('--')) usage()
  const value = args[index + 1]
  if (!value || value.startsWith('--')) usage()
  options[key.slice(2)] = value
  index += 1
}

const entity = String(options.entity || '').trim()
const inputPath = path.resolve(String(options.input || ''))
const outputPath = path.resolve(String(options.output || ''))
const idField = String(options['id-field'] || 'id')
const outletField = String(options['outlet-field'] || 'outlet_id')
const businessDateField = String(options['business-date-field'] || '')
const statusField = String(options['status-field'] || 'status')
const sentinels = new Set(
  String(options['normalize-deleted-at-sentinels'] || '')
    .split(',')
    .map((value) => value.trim())
    .filter(Boolean),
)

if (!entity || !inputPath || !outputPath) usage()
if (!existsSync(inputPath)) throw new Error(`Input does not exist: ${inputPath}`)
if (!/^[A-Za-z][A-Za-z0-9_]*$/.test(entity)) throw new Error(`Invalid entity: ${entity}`)

const parsed = JSON.parse(readFileSync(inputPath, 'utf8'))
const sourceRecords = Array.isArray(parsed) ? parsed : parsed.records
if (!Array.isArray(sourceRecords) || !sourceRecords.length) throw new Error('Input contains no records')

function text(value) {
  if (value === null || value === undefined) return ''
  return String(value)
}

function isoDate(value) {
  const raw = text(value).trim()
  return /^\d{4}-\d{2}-\d{2}/.test(raw) ? raw.slice(0, 10) : ''
}

function sqlString(value) {
  return `'${text(value).replaceAll("'", "''")}'`
}

function cleanRecord(record) {
  if (!record || typeof record !== 'object' || Array.isArray(record)) {
    throw new Error('Every input record must be a JSON object')
  }
  const clean = structuredClone(record)
  const deletedAt = text(clean.deleted_at).trim()
  if (sentinels.has(deletedAt)) clean.deleted_at = ''
  return clean
}

const records = sourceRecords.map(cleanRecord)
const ids = records.map((record) => text(record[idField]).trim())
if (ids.some((id) => !id)) throw new Error(`At least one record has a blank ${idField}`)
const duplicates = [...new Set(ids.filter((id, index) => ids.indexOf(id) !== index))]
if (duplicates.length) throw new Error(`Duplicate IDs in source: ${duplicates.slice(0, 20).join(', ')}`)

const sql = [
  `-- Generated by scripts/ops/build-safe-backfill.mjs`,
  `-- Entity: ${entity}`,
  `-- Source SHA-256: ${createHash('sha256').update(readFileSync(inputPath)).digest('hex')}`,
  `-- Rows: ${records.length}`,
  `-- Safety: INSERT into ops_records only; existing (entity, entity_id) rows are preserved.`,
  '',
]

for (const record of records) {
  const id = text(record[idField]).trim()
  const outletId = text(record[outletField]).trim()
  const businessDate = businessDateField ? isoDate(record[businessDateField]) : ''
  const deletedAt = text(record.deleted_at).trim()
  const status = deletedAt ? 'deleted' : (text(record[statusField]).trim() || 'active')
  const version = Number.isInteger(Number(record.version)) && Number(record.version) > 0
    ? Number(record.version)
    : 1
  const createdAt = text(record.created_date || record.created_at || record.updated_date || record.updated_at).trim()
  const updatedAt = text(record.updated_date || record.updated_at || record.created_date || record.created_at).trim()
  const createdBy = text(record.created_by).trim()
  const updatedBy = text(record.updated_by).trim()
  const payloadJson = JSON.stringify(record)

  sql.push(
    `INSERT INTO ops_records (`
      + `entity, entity_id, outlet_id, business_date, status, payload_json, `
      + `version, created_at, created_by, updated_at, updated_by, deleted_at`
      + `) VALUES (`
      + `${sqlString(entity)}, ${sqlString(id)}, ${sqlString(outletId)}, ${sqlString(businessDate)}, `
      + `${sqlString(status)}, ${sqlString(payloadJson)}, ${version}, ${sqlString(createdAt)}, `
      + `${sqlString(createdBy)}, ${sqlString(updatedAt)}, ${sqlString(updatedBy)}, ${sqlString(deletedAt)}`
      + `) ON CONFLICT(entity, entity_id) DO NOTHING;`,
  )
}

writeFileSync(outputPath, `${sql.join('\n')}\n`)
const manifestPath = `${outputPath}.manifest.json`
writeFileSync(manifestPath, `${JSON.stringify({
  generated_at: new Date().toISOString(),
  entity,
  input: inputPath,
  output: outputPath,
  row_count: records.length,
  unique_id_count: new Set(ids).size,
  ids,
  normalization: {
    deleted_at_sentinels: [...sentinels],
  },
  safety: {
    connects_to_d1: false,
    insert_table: 'ops_records',
    conflict_behavior: 'DO NOTHING',
    updates_existing_rows: false,
    deletes_rows: false,
    writes_ops_mutations: false,
    writes_sheet_sync_outbox: false,
  },
}, null, 2)}\n`)

console.log('SAFE_BACKFILL_SQL_GENERATED=true')
console.log(`ENTITY=${entity}`)
console.log(`ROWS=${records.length}`)
console.log(`SQL=${outputPath}`)
console.log(`MANIFEST=${manifestPath}`)
